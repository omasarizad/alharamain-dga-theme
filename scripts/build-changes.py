import markdown

START_SUBJECT = "Rebuild the homepage in Tailwind"   # first commit shown in the log
MAX_LINE = 300
MAX_DIFF_LINES = 400
REPO = "https://github.com/omasarizad/alharamain-dga-theme"


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout


# ---- Snippets from build-home.py ---------------------------------------------

def load_home():
    spec = importlib.util.spec_from_file_location("build_home", "scripts/build-home.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def snippets():
    h = load_home()
    d = json.loads(Path("data/content.json").read_text(encoding="utf-8"))
    card_item = d["sections"]["memory"]["items"][0]
    drawer = h.drawer(d)
    first_item = re.search(r"<li>.*?</li>", drawer, re.S).group(0)
    return {
        "header": h.header(d),
        "drawer-item": first_item,
        "alert": h.inline_alert("البث المباشر للدروس", "تابع الدروس العلمية المنقولة مباشرة."),
        "button": h.button("عرض الكل", "secondary-outline", "md") + "\n" + h.button("بحث", "primary", "lg"),
        "tabs": h.tabs(h.PLACE_TABS, "memory", "all", "تصفية حسب المكان"),
        "card": h.card(card_item),
        "tag": h.tag("الأذان"),
        "search": h.search_box("ابحث عن درس، خطبة، تلاوة، أو شيخ"),
        "featured-icon": h.featured_icon("quran-01"),
    }


def pretty(markup):
    """Light formatting: one tag per line, so long class lists stay readable."""
    markup = re.sub(r"\s*\n\s*", "", markup.strip())
    markup = re.sub(r"(>)(<)", r"\1\n\2", markup)
    out, depth = [], 0
    for line in markup.split("\n"):
        if re.match(r"</", line):
            depth = max(depth - 1, 0)
        out.append("  " * depth + line)
        if re.match(r"<(?!/)(?!img|input|br)[^>]*[^/]>$", line) and not re.search(r"</[^>]+>$", line):
            depth += 1
    return "\n".join(out)


def render_guide():
    src = Path("DEV-GUIDE.md").read_text(encoding="utf-8")
    snips = snippets()

    def repl(m):
        name = m.group(1)
        code = html.escape(pretty(snips[name]))
        return (f'<details class="snippet" open><summary>HTML: <code>{name}</code> '
                f'<button type="button" class="copy" data-copy>Copy</button></summary><pre><code>{code}</code></pre></details>')

    body = markdown.markdown(src, extensions=["tables", "fenced_code"])
    body = re.sub(r"<!-- snippet:([\w-]+) -->", repl, body)
    # Turn h2/h3 into anchors for the table of contents
    toc = []

    def anchor(m):
        level, text = m.group(1), m.group(2)
        slug = re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", text).lower()).strip("-")
        if level == "2":
            toc.append(f'<a href="#{slug}">{re.sub(r"<[^>]+>", "", text)}</a>')
        return f'<h{level} id="{slug}">{text}</h{level}>'

    body = re.sub(r"<h([23])>(.*?)</h\1>", anchor, body)
    return body, "".join(toc)


# ---- Commit log --------------------------------------------------------------

def commits():
    sep, end = "\x1f", "\x1e"
    fmt = sep.join(["%H", "%h", "%an", "%aI", "%s", "%b"]) + end
    out = []
    for rec in git("log", f"--format={fmt}").split(end):
        rec = rec.strip("\n")
        if not rec:
            continue
        full, short, author, date, subject, body = rec.split(sep)
        out.append(dict(full=full, short=short, author=author, date=date, subject=subject, body=body.strip()))
        if subject.startswith(START_SUBJECT):
            return out
    return []   # start commit not made yet


def file_diffs(sha):
    stats = {}
    for line in git("show", "--numstat", "--format=", sha).splitlines():
        a, r, path = line.split("\t", 2)
        stats[path] = (a, r)
    status = dict(reversed(l.split("\t", 1)) for l in git("show", "--name-status", "--format=", sha).splitlines())
    for path, (a, r) in stats.items():
        if path.endswith(".png"):
            yield path, status.get(path, "M"), a, r, []
            continue
        diff = git("show", "--format=", "--unified=2", sha, "--", path).splitlines()
        yield path, status.get(path, "M"), a, r, [l for l in diff if not l.startswith(("diff --git", "index ", "--- ", "+++ "))]


def render_diff(lines):
    out = []
    for l in lines[:MAX_DIFF_LINES]:
        cls = {"+": "add", "-": "del", "@": "hunk"}.get(l[:1], "ctx")
        text = l if len(l) <= MAX_LINE else l[:MAX_LINE] + f"  … [+{len(l) - MAX_LINE} chars]"
        out.append(f'<span class="{cls}">{html.escape(text)}</span>')
    if len(lines) > MAX_DIFF_LINES:
        out.append(f'<span class="hunk">… {len(lines) - MAX_DIFF_LINES} more lines (see git)</span>')
    return "\n".join(out)


def render_log():
    labels = {"A": "added", "M": "modified", "D": "deleted", "R": "renamed"}
    items = []
    for c in commits():
        files = "".join(
            f'<details><summary><span class="st st-{st[0]}">{labels.get(st[0], st)}</span><code>{html.escape(p)}</code>'
            f'<span class="num"><b class="add">+{a}</b> <b class="del">−{r}</b></span></summary>'
            f'{f"<pre>{render_diff(body)}</pre>" if body else ""}</details>'
            for p, st, a, r, body in file_diffs(c["full"])
        )
        body = "".join(f"<p>{html.escape(p)}</p>" for p in c["body"].split("\n\n") if p and not p.startswith("Co-Authored-By"))
        items.append(
            f'<article class="commit"><h3>{html.escape(c["subject"])}</h3>'
            f'<div class="meta"><a href="{REPO}/commit/{c["full"]}">{c["short"]}</a> · {html.escape(c["author"])} · '
            f'<time datetime="{c["date"]}">{c["date"][:16].replace("T", " ")}</time></div>{body}<div class="files">{files}</div></article>'
        )
    return "\n".join(items) or '<p class="muted">No commits yet.</p>', len(items)


