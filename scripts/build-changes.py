#!/usr/bin/env python3
"""Generate changes.html for developers updating the real site:

1. DEV-GUIDE.md rendered to HTML. `<!-- snippet:NAME -->` markers are replaced
   with markup generated by scripts/build-home.py, so snippets never go stale.
2. The commit log, starting at the Tailwind rebuild (earlier attempts are
   intentionally left out), with per-file diffs.

Run from the repo root: python3 scripts/build-changes.py
CI runs it on every push to main before deploying GitHub Pages.
"""
import html
import importlib.util
import json
import re
import subprocess
