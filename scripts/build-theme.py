#!/usr/bin/env python3
"""Generate tailwind/platforms-code.css: a Tailwind v4 @theme with the official
Platforms Code tokens, read straight from @platformscode/core's core.css.

Run from the repo root: python3 scripts/build-theme.py
Copy the output into the real site's Tailwind v4 setup (see changes.html).

Naming, so classes read naturally in Tailwind:
  --colors-primary-sa-flag-600-primary  ->  --color-primary-600   (bg-primary-600)
  --colors-secondary-gold-600-primary   ->  --color-gold-600      (text-gold-600)
  --colors-tertiary-lavendar-500-...    ->  --color-lavender-500
  --colors-neutral-800                  ->  --color-neutral-800
  --colors-green/blue/yellow/red-700    ->  --color-success/info/warning/error-700
  --radius-sm (4px) / md (8px) / lg (16px) / xl (24px)
  .display-lg-bold  (48px/60px)         ->  text-display-lg
  .text-md-regular  (16px/24px)         ->  text-md
"""
import re
import subprocess
import tarfile
from pathlib import Path

VERSION = "0.0.53"
CACHE = Path(".cache/platformscode-core")
OUT = Path("tailwind/platforms-code.css")

FAMILIES = {
    "primary-sa-flag": "primary",
    "secondary-gold": "gold",
    "tertiary-lavendar": "lavender",
    "neutral": "neutral",
    "green": "success",
    "blue": "info",
    "yellow": "warning",
    "red": "error",
}


def core_css():
    css = CACHE / "package/dist/core/core.css"
    if not css.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        name = subprocess.run(["npm", "pack", f"@platformscode/core@{VERSION}", "--silent", "--pack-destination", str(CACHE)],
                              capture_output=True, text=True, check=True).stdout.strip().splitlines()[-1]
        with tarfile.open(CACHE / name) as t:
            t.extractall(CACHE)
    return css.read_text(encoding="utf-8")


def main():
    s = core_css()
    tokens = {}
    for m in re.finditer(r"(--[a-zA-Z0-9-]+):([^;}]+)", s):
        tokens.setdefault(m.group(1), m.group(2).strip())   # first = light theme

    lines = [f"/* Generated by scripts/build-theme.py from @platformscode/core@{VERSION} core.css. Do not edit. */",
             "@theme {",
             "  /* Disable Tailwind's default palette so only Platforms Code colors exist */",
             "  --color-*: initial;",
             f"  --color-white: {tokens['--colors-base-white']};",
             f"  --color-black: {tokens['--colors-base-black']};",
             "  --color-transparent: transparent;",
             "  --color-current: currentColor;"]
    for fam, alias in FAMILIES.items():
        lines.append(f"\n  /* {fam} -> {alias} */")
        for k, v in tokens.items():
            m = re.fullmatch(rf"--colors-{re.escape(fam)}-(\d+)(?:-primary)?", k)
            if m and v.startswith("#"):
                lines.append(f"  --color-{alias}-{m.group(1)}: {v};")

    lines.append("\n  /* Radius */")
    for name in ["none", "xs", "sm", "md", "lg", "xl", "full"]:
        v = tokens.get(f"--radius-{name}", "")
        v = re.sub(r"var\((--radius-[\w-]+)\)", lambda m: tokens.get(m.group(1), m.group(0)), v)
        lines.append(f"  --radius-{name}: {v};")

    lines.append("\n  /* Shadows */")
    for k, v in tokens.items():
        m = re.fullmatch(r"--shadow-(xs|sm|md|lg|xl|2xl|3xl)", k)
        if m:
            lines.append(f"  --shadow-{m.group(1)}: {v};")

    lines.append('\n  /* Typography */')
    lines.append('  --font-sans: "IBM Plex Sans Arabic", "IBM Plex Sans", system-ui, -apple-system, "Segoe UI", "Noto Sans Arabic", sans-serif;')
    sizes = {}
    for m in re.finditer(r"\.(display|text)-(2xl|xl|lg|md|sm|xs|2xs)-(?:regular|medium|semibold|bold)\{font:\d+ (\d+)px/(\d+)px", s):
        sizes.setdefault(f"{'display-' if m.group(1) == 'display' else ''}{m.group(2)}", (m.group(3), m.group(4)))
    # text-md isn't a font-shorthand class in core.css; 16px/24px is what the
    # official components compute to (search input, alert title).
    sizes.setdefault("md", ("16", "24"))
    order = ["display-2xl", "display-xl", "display-lg", "display-md", "display-sm", "display-xs",
             "xl", "lg", "md", "sm", "xs", "2xs"]
    for name in order:
        if name in sizes:
            fs, lh = sizes[name]
            lines.append(f"  --text-{name}: {int(fs) / 16:g}rem;  /* {fs}px */")
            lines.append(f"  --text-{name}--line-height: {lh}px;")
    lines.append("}")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    n_colors = sum(1 for l in lines if l.strip().startswith("--color-"))
    print(f"{OUT}: {n_colors} colors, {len(sizes)} text sizes")


if __name__ == "__main__":
    main()
